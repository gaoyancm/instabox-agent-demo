import hashlib
import io
import json
import re
from pathlib import Path
import zipfile
from .common import TaskError, identifier

ROOT = "/data/instabox-agent-demo"


class JobRunner:
    def __init__(self, api, task_id, source_root, profile="basic"):
        self.api, self.task_id = api, identifier(task_id)
        self.source_root = Path(source_root)
        self.release = None
        self.profile = profile
        self.python = "python3"
        if profile != "basic" and not (self.source_root / "vendor/manifest.json").exists():
            raise TaskError("prepare_remote_dependencies_first")
        if profile == "collection" and not json.loads((self.source_root / "config/collection-sources.json").read_text()):
            raise TaskError("no_collection_sources_configured")

    def deploy(self):
        buffer = io.BytesIO()
        with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
            for directory in ["automation", "config", "fixtures", "browser", "vendor"]:
                for path in sorted((self.source_root / directory).rglob("*")):
                    if path.is_file() and "__pycache__" not in path.parts:
                        archive.write(path, path.relative_to(self.source_root).as_posix())
        data = buffer.getvalue()
        digest = hashlib.sha256(data).hexdigest()
        self.release = f"{ROOT}/releases/{digest}"
        archive_path = f"{ROOT}/uploads/{digest}.zip"
        self.api.upload(archive_path, data)
        # All archive members are generated by this application, never supplied by a web source.
        script = ("import hashlib,pathlib,sys,zipfile; p=pathlib.Path(sys.argv[1]); "
                  "assert hashlib.sha256(p.read_bytes()).hexdigest()==sys.argv[3]; "
                  "zipfile.ZipFile(p).extractall(sys.argv[2])")
        self.api.exec(["python3", "-c", script, archive_path, self.release, digest])
        return digest

    def prepare_runtime(self):
        if self.profile != "basic":
            dependency_digest = hashlib.sha256((self.source_root / "vendor/manifest.json").read_bytes()).hexdigest()
            environment = f"{ROOT}/runtime/{dependency_digest}"
            bootstrap = ("import pathlib,hashlib,json,subprocess,sys; release=pathlib.Path(sys.argv[1]); "
                         "vendor=release/'vendor'; manifest=json.loads((vendor/'manifest.json').read_text()); "
                         "assert all(hashlib.sha256((vendor/n).read_bytes()).hexdigest()==h for n,h in manifest.items()); "
                         "subprocess.run(['python3','-m','venv',sys.argv[2]],check=True,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL); "
                         "subprocess.run([sys.argv[2]+'/bin/python','-m','pip','install','--no-index','--find-links',str(vendor),"
                         "'httpx==0.28.1','jsonschema==4.26.0'],check=True,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)")
            self.api.exec(["python3", "-c", bootstrap, self.release, environment])
            self.python = environment + "/bin/python"

    def call(self, action, *extra):
        if not self.release:
            raise TaskError("job_not_deployed")
        # argv contains only fixed control code, validated ID and explicit arguments.
        script = "import os,runpy,sys; os.chdir(sys.argv.pop(1)); sys.path.insert(0,os.getcwd()); runpy.run_module('automation.remote',run_name='__main__')"
        output = self.api.exec([self.python, "-c", script, self.release, action, self.task_id, *extra])
        try:
            return json.loads(output)
        except ValueError:
            raise TaskError("job_protocol_error") from None

    def inspect(self):
        return self.call("inspect")

    def network(self):
        return self.call("network")

    def start(self, seconds):
        return self.call("start", "--seconds", str(seconds), "--profile", self.profile)

    def status(self):
        return self.call("status")

    def stop(self):
        return self.call("stop")

    def collect(self, destination):
        info = self.call("package")
        data = self.api.download(info["path"])
        if hashlib.sha256(data).hexdigest() != info["sha256"]:
            raise TaskError("result_hash_mismatch")
        destination = Path(destination)
        destination.mkdir(parents=True, exist_ok=True)
        (destination / "result.zip").write_bytes(data)
        with zipfile.ZipFile(io.BytesIO(data)) as archive:
            allowed = {"status.json", "identity.json", "results.jsonl", "results.manifest.json", "backup.sqlite",
                       "job.log", "acceptance-report.json", "dependencies.json"}
            if any(name not in allowed and not re.fullmatch(r"browser/[0-9]+/(page\.png|record\.json)", name)
                   and not re.fullmatch(r"public/(public-report\.json|public-results\.jsonl|public-results\.manifest\.json|public-backup\.sqlite)", name)
                   for name in archive.namelist()):
                raise TaskError("unsafe_result_archive")
            archive.extractall(destination)
        required = ["status.json", "results.jsonl", "results.manifest.json", "backup.sqlite"]
        if any(not (destination / name).exists() for name in required):
            raise TaskError("result_incomplete")
        manifest = json.loads((destination / "results.manifest.json").read_text())
        payload = (destination / "results.jsonl").read_bytes()
        if hashlib.sha256(payload).hexdigest() != manifest["sha256"]:
            raise TaskError("result_manifest_mismatch")
        from .records import validate_record
        records = [json.loads(line) for line in payload.decode("utf-8").splitlines()]
        if len(records) != manifest["count"]:
            raise TaskError("result_count_mismatch")
        for record in records:
            validate_record(record)
            if record["status"] != "error" and hashlib.sha256(record["content"].encode()).hexdigest() != record["content_hash"]:
                raise TaskError("record_content_hash_mismatch")
        from .storage import restore_backup, Store
        backup_digest = hashlib.sha256((destination / "backup.sqlite").read_bytes()).hexdigest()
        restored = destination / "restored" / backup_digest
        # Each artifact is collected once into its task-specific output directory.
        if not (restored / "records.sqlite").exists():
            restore_backup(destination / "backup.sqlite", restored)
        recovered = Store(restored)
        try:
            if recovered.records(self.task_id) != records:
                raise TaskError("backup_restore_content_mismatch")
        finally:
            recovered.close()
        manifest["external_backup_restore_verified"] = True
        if self.profile in {"full", "full-public"}:
            if not (destination / "acceptance-report.json").exists():
                raise TaskError("stage_d_incomplete")
            acceptance = json.loads((destination / "acceptance-report.json").read_text())
            if not acceptance.get("passed") or not all(acceptance["checks"].values()):
                raise TaskError("stage_d_acceptance_failed")
        return manifest
